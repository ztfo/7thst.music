#!/usr/bin/env node

/**
 * Cut a song for the site, upload it to Cloudinary, and record its room envelope.
 *
 *   node scripts/cut-and-upload-audio.js --src "<file>" --id el-fuego --kind preview
 *   node scripts/cut-and-upload-audio.js --src "<file>" --id la-luna --kind full
 *
 * full     the whole song, for cards that are out (mp3 256k)
 * preview  30 seconds from a third of the way in, faded in and out (mp3 192k).
 *          Unreleased songs only ever go up as a preview, never in full.
 *
 * Options: --start <seconds> overrides where a preview starts; --dry skips the upload.
 * Re-running with the same --id replaces the file at the same address, so a
 * remaster drops in without touching the site. Needs ffmpeg and the .env credentials.
 */

require('dotenv').config();
const cloudinary = require('cloudinary').v2;
const { execFileSync } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');

const PREVIEW = 30;
const FADE_IN = 1.2;
const FADE_OUT = 2;
const HOP = 0.03;
const ENVELOPES = path.join(__dirname, '..', 'data', 'envelopes.js');

const args = {};
process.argv.slice(2).forEach((a, i, all) => {
  if (a.startsWith('--')) args[a.slice(2)] = all[i + 1] && !all[i + 1].startsWith('--') ? all[i + 1] : true;
});
if (!args.src || !args.id || !['full', 'preview'].includes(args.kind)) {
  console.error('Usage: --src <file> --id <card-id> --kind full|preview [--start <seconds>] [--dry]');
  process.exit(1);
}

const duration = (file) => Number(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file]).toString().trim());

function encode(src, out, kind, start) {
  const common = ['-y', '-v', 'error', '-i', src, '-map_metadata', '-1', '-ac', '2', '-ar', '44100', '-codec:a', 'libmp3lame'];
  if (kind === 'full') return execFileSync('ffmpeg', [...common, '-b:a', '256k', out]);
  const filter = `atrim=start=${start}:duration=${PREVIEW},asetpts=PTS-STARTPTS,afade=t=in:d=${FADE_IN},afade=t=out:st=${PREVIEW - FADE_OUT}:d=${FADE_OUT}`;
  return execFileSync('ffmpeg', [...common, '-af', filter, '-b:a', '192k', out]);
}

// The room breathes with the low end: the same reading the browser used to make,
// done once here so phones never download a song twice or decode it.
function envelope(file) {
  const sr = 22050;
  const pcm = execFileSync('ffmpeg', ['-v', 'error', '-i', file, '-ac', '1', '-ar', String(sr), '-f', 'f32le', '-'], { maxBuffer: 1 << 30 });
  const x = new Float32Array(pcm.buffer, pcm.byteOffset, pcm.length / 4);
  const hop = Math.round(sr * HOP);
  const n = Math.floor(x.length / hop);
  const low = new Float32Array(n);
  const k = 1 - Math.exp((-2 * Math.PI * 140) / sr);
  let lp = 0;
  for (let f = 0; f < n; f++) {
    let sum = 0;
    for (let j = f * hop, end = j + hop; j < end; j++) { lp += k * (x[j] - lp); sum += lp * lp; }
    low[f] = Math.sqrt(sum / hop);
  }
  const top = Float32Array.from(low).sort()[Math.floor(n * 0.96)] || 1;
  const bytes = new Uint8Array(n);
  const onsets = [];
  let avg = 0;
  let last = -99;
  for (let f = 0; f < n; f++) {
    const v = Math.min(1.2, low[f] / top);
    if (v > avg * 1.3 && v > 0.42 && f - last > 7) { onsets.push(f); last = f; }
    avg = avg * 0.9 + v * 0.1;
    bytes[f] = Math.round((v / 1.2) * 255);
  }
  return { hop: HOP, low: Buffer.from(bytes).toString('base64'), onsets };
}

function saveEnvelope(id, env) {
  const text = fs.existsSync(ENVELOPES) ? fs.readFileSync(ENVELOPES, 'utf8') : '';
  const all = text ? JSON.parse(text.slice(text.indexOf('{'), text.lastIndexOf('}') + 1)) : {};
  all[id] = env;
  const sorted = Object.fromEntries(Object.keys(all).sort().map((key) => [key, all[key]]));
  fs.writeFileSync(ENVELOPES, `// Generated by scripts/cut-and-upload-audio.js: each song's low-end energy (0-255 per 30 ms) and its kicks.\nexport default ${JSON.stringify(sorted, null, 1)};\n`);
}

(async () => {
  const full = duration(args.src);
  const start = args.kind === 'preview' ? Number(args.start ?? Math.round(full * 0.32)) : 0;
  const publicId = `${args.id}${args.kind === 'preview' ? '-preview' : ''}`;
  const out = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'bs-audio-')), `${publicId}.mp3`);
  encode(args.src, out, args.kind, start);
  const env = envelope(out);
  console.log(`${args.id}: ${args.kind}, song ${full.toFixed(1)}s${args.kind === 'preview' ? `, clip from ${start}s` : ''}, ${(fs.statSync(out).size / 1e6).toFixed(1)} MB, ${env.onsets.length} kicks`);

  if (!args.dry) {
    const { CLOUDINARY_CLOUD_NAME, CLOUDINARY_API_KEY, CLOUDINARY_API_SECRET } = process.env;
    if (!CLOUDINARY_CLOUD_NAME || !CLOUDINARY_API_KEY || !CLOUDINARY_API_SECRET) {
      console.error('Missing Cloudinary credentials in .env');
      process.exit(1);
    }
    cloudinary.config({ cloud_name: CLOUDINARY_CLOUD_NAME, api_key: CLOUDINARY_API_KEY, api_secret: CLOUDINARY_API_SECRET, secure: true });
    const res = await cloudinary.uploader.upload(out, { resource_type: 'video', public_id: `buena-suerte/${publicId}`, overwrite: true, invalidate: true });
    console.log(`  uploaded: https://res.cloudinary.com/${CLOUDINARY_CLOUD_NAME}/video/upload/buena-suerte/${publicId}.mp3 (${res.bytes} bytes)`);
  }
  saveEnvelope(args.id, { ...env, dur: Math.round(full) });
  fs.rmSync(path.dirname(out), { recursive: true, force: true });
})().catch((err) => {
  console.error(err.message || err);
  process.exit(1);
});
